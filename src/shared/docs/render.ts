/**
 * Templates: one renderer per document, each built only from Evidence. A renderer either returns
 * the document's managed sections or says why the document does not apply (nothing in the source to
 * describe) — it never fills a gap with invented content. Facts the engine could not verify are
 * written into the document as "Unverified" notes, and also returned in `uncertain`.
 */


export interface DocTarget {
  path: string;
  doc: DocId;
  category: DocCategory;
  title: string;
  /** Managed Markdown sections. Absent for a whole-file target (`whole`). */
  sections?: ManagedSection[];
  /** A file PawOS owns entirely (Mermaid sources, a new ADR). */
  whole?: string;
  /** True for a file that is written once and then belongs to the user (ADRs). */
  createOnly?: boolean;
  uncertain: string[];
  /** Source files this target describes (sync mode narrows component pages with it). */
  sources?: string[];
}


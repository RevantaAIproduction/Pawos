// ── small Markdown helpers ──────────────────────────────────────────────────────────────────────

export function cell(text: string): string {
  return text.replace(/\r?\n/g, ' ').replace(/\|/g, '\\|').trim() || ' ';
}

export function code(text: string): string {
  const t = text.replace(/\r?\n/g, ' ');
  return t.includes('`') ? `\`\` ${t} \`\`` : `\`${t}\``;
}

function table(headers: string[], rows: string[][]): string {
  return [`| ${headers.join(' | ')} |`, `| ${headers.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');
}

/** The first sentence of a description, at most 200 characters — enough for a table cell. */
export function brief(text: string | undefined): string {
  if (!text) return '';
  const first = /^[\s\S]*?[.!?](?=\s|$)/.exec(text)?.[0] ?? text;
  return first.length > 200 ? `${first.slice(0, 197).trimEnd()}…` : first;
}

function unverified(text: string): string {
  return `> **Unverified:** ${text}`;
}

function list(items: string[], empty: string): string {
  return items.length > 0 ? items.map((i) => `- ${i}`).join('\n') : `_${empty}_`;
}

/** A relative Markdown link from one document to a repository path. */
export function relLink(fromDoc: string, target: string): string {
  const fromParts = dirname(fromDoc).split('/').filter(Boolean);
  const toParts = target.split('/');
  let common = 0;
  while (common < fromParts.length && common < toParts.length - 1 && fromParts[common] === toParts[common]) common++;
  const up = fromParts.length - common;
  const rel = `${'../'.repeat(up)}${toParts.slice(common).join('/')}`;
  return rel.replace(/ /g, '%20');
}

function fileLink(fromDoc: string, target: string): string {
  return `[${code(target)}](${relLink(fromDoc, target)})`;
}

function section(id: string, body: string): ManagedSection {
  return { id, body };
}

function packageManager(ev: Evidence): string {
  if (ev.paths.includes('pnpm-lock.yaml')) return 'pnpm';
  if (ev.paths.includes('yarn.lock')) return 'yarn';
  if (ev.paths.includes('bun.lockb') || ev.paths.includes('bun.lock')) return 'bun';
  return 'npm';
}

function runScript(pm: string, name: string): string {
  if (pm === 'npm') return name === 'test' || name === 'start' ? `npm ${name}` : `npm run ${name}`;
  return `${pm} ${name}`;
}

function truncatedNote(ev: Evidence): string[] {
  return ev.truncated ? ['The project is larger than PawOS reads in one pass; some files were not analysed, so lists here may be incomplete.'] : [];
}

// ── Type 1: product and project ─────────────────────────────────────────────────────────────────

export function renderReadme(ev: Evidence, docTargets: string[]): RenderOutcome {
  const path = DOC_PATHS.readme;
  const uncertain = [...truncatedNote(ev)];
  const overview: string[] = [];
  if (ev.description) overview.push(ev.description);
  else {
    uncertain.push('package.json has no description, so the project summary is left for you to write.');
    overview.push(unverified('No project description was found in package.json. Add one above this block.'));
  }
  if (ev.stack.length > 0) overview.push(`**Built with:** ${ev.stack.join(', ')}.`);
  if (ev.rootPackage?.version) overview.push(`**Version:** ${ev.rootPackage.version}`);

  const pm = packageManager(ev);
  const scripts = ev.rootPackage?.scripts ?? {};
  const start: string[] = [];
  if (ev.rootPackage) {
    start.push('```bash', pm === 'npm' ? 'npm install' : `${pm} install`);
    for (const name of ['dev', 'start', 'build', 'test', 'lint', 'typecheck']) if (scripts[name]) start.push(runScript(pm, name));
    start.push('```');
    const engines = Object.entries(ev.rootPackage.engines).map(([k, v]) => `${k} ${v}`);
    if (engines.length > 0) start.push('', `Requires ${engines.join(', ')}.`);
    const other = Object.keys(scripts).filter((n) => !['dev', 'start', 'build', 'test', 'lint', 'typecheck'].includes(n));
    if (other.length > 0) start.push('', `Other scripts: ${other.slice(0, 20).map(code).join(', ')}${other.length > 20 ? `, and ${other.length - 20} more` : ''}.`);
  } else {
    start.push(unverified('No package.json at the project root, so the install and run commands are not known.'));
    uncertain.push('No root package.json: getting-started commands are not documented.');
  }

  const sections: ManagedSection[] = [section('overview', overview.join('\n\n')), section('getting-started', `## Getting started\n\n${start.join('\n')}`)];
  if (ev.env.length > 0) {
    sections.push(
      section(
        'configuration',
        `## Configuration\n\nThe code reads these environment variables (names only — set the values in your own environment, never in the repository):\n\n${table(['Variable', 'Read in'], ev.env.slice(0, 60).map((e) => [code(e.name), e.sources.slice(0, 3).map(code).join(', ') + (e.sources.length > 3 ? ` +${e.sources.length - 3}` : '')]))}`
      )
    );
  }
  if (ev.modules.modules.length > 0) {
    sections.push(section('structure', `## Project structure\n\n${table(['Area', 'Source files'], ev.modules.modules.map((m) => [code(m.name), String(m.files)]))}`));
  }
  const docs = docTargets.filter((p) => p !== path).sort();
  if (docs.length > 0) sections.push(section('documentation', `## Documentation\n\n${docs.map((d) => `- [${d}](${relLink(path, d)})`).join('\n')}`));
  return { targets: [{ path, doc: 'readme', category: 'product', title: ev.name, sections, uncertain }] };
}

export interface PlanSection {
  title: string;
  body: string;
}

/** Headings (#..####, or a bold line) split an approved plan into sections. */
export function parsePlanSections(markdown: string): PlanSection[] {
  const lines = markdown.replace(/\r\n/g, '\n').split('\n');
  const out: PlanSection[] = [];
  let current: PlanSection | null = null;
  let inFence = false;
  for (const line of lines) {
    if (/^\s*```/.test(line)) inFence = !inFence;
    const heading = inFence ? null : /^\s*(?:#{1,4}\s+(.+?)\s*#*\s*$|\*\*([^*]{2,80})\*\*\s*:?\s*$)/.exec(line);
    if (heading) {
      if (current && current.body.trim()) out.push({ title: current.title, body: current.body.trim() });
      current = { title: (heading[1] ?? heading[2] ?? '').replace(/[:*]+$/, '').trim(), body: '' };
      continue;
    }
    if (!current) current = { title: 'Overview', body: '' };
    current.body += `${line}\n`;
  }
  if (current && current.body.trim()) out.push({ title: current.title, body: current.body.trim() });
  return out.filter((s) => !/^project\s+(plan|blueprint)$/i.test(s.title) || s.body.length > 0);
}

const PLAN_ROUTES: { doc: 'prd' | 'requirements' | 'implementation-plan'; re: RegExp }[] = [
  { doc: 'requirements', re: /requirement|acceptance|constraint|non-?functional|security|performance|compliance|data model|data|schema|integration|permission/i },
  { doc: 'implementation-plan', re: /implementation|architecture|frontend|backend|phase|milestone|step|task|testing|test|build|deploy|preview|visual qa|qa|timeline|rollout|plan/i },
  { doc: 'prd', re: /.*/ },
];

function slug(text: string): string {
  return text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 48) || 'section';
}

export function planDocFor(title: string): 'prd' | 'requirements' | 'implementation-plan' {
  return (PLAN_ROUTES.find((r) => r.re.test(title)) ?? { doc: 'prd' as const }).doc;
}

export function renderFromPlan(ev: Evidence, plan: ApprovedPlan | undefined, which: 'prd' | 'requirements' | 'implementation-plan'): RenderOutcome {
  const path = DOC_PATHS[which];
  const uncertain: string[] = [];
  const sections: ManagedSection[] = [];
  const title = which === 'prd' ? 'Product Requirements' : which === 'requirements' ? 'Requirements' : 'Implementation Plan';
  if (plan && plan.markdown.trim()) {
    const parts = parsePlanSections(plan.markdown).filter((s) => planDocFor(s.title) === which);
    const used = new Set<string>();
    for (const part of parts) {
      let id = `plan-${slug(part.title)}`;
      for (let n = 2; used.has(id); n++) id = `plan-${slug(part.title)}-${n}`;
      used.add(id);
      sections.push(section(id, `## ${part.title}\n\n${part.body}`));
    }
    if (sections.length === 0 && which !== 'prd') return { notApplicable: `The approved plan has no ${which === 'requirements' ? 'requirements' : 'implementation'} sections.` };
    if (plan.title && which === 'prd') sections.unshift(section('plan-title', `**Plan:** ${plan.title}`));
  }
  if (which === 'prd') {
    const current: string[] = [];
    if (ev.pages.length > 0) current.push(`Pages in the code today: ${ev.pages.slice(0, 30).map((p) => code(p.route)).join(', ')}${ev.pages.length > 30 ? `, and ${ev.pages.length - 30} more` : ''}.`);
    if (ev.features.length > 0) current.push(`Features PawOS found in the code: ${ev.features.slice(0, 30).map((f) => f.name).join(', ')}.`);
    if (ev.api.length > 0) current.push(`${ev.api.length} API endpoint${ev.api.length === 1 ? '' : 's'} (see [the API reference](${relLink(path, DOC_PATHS.api)})).`);
    if (current.length > 0) sections.push(section('current-state', `## What exists in the repository\n\n${current.join('\n\n')}`));
    if (!plan) {
      uncertain.push('Product goals, users and success measures are not in the source code; they need your input.');
      sections.push(section('needs-input', `## Goals and users\n\n${unverified('Product goals, target users and success measures cannot be read from code. Write them outside this block, or approve a project plan and save it as documentation.')}`));
    }
  } else if (which === 'requirements' && !plan) {
    const req: string[] = [];
    const engines = Object.entries(ev.rootPackage?.engines ?? {});
    if (engines.length > 0) req.push(`- Runtime: ${engines.map(([k, v]) => `${k} ${v}`).join(', ')}`);
    if (ev.env.length > 0) req.push(`- Configuration: ${ev.env.length} environment variable${ev.env.length === 1 ? '' : 's'} must be set (see README).`);
    if (ev.schema.tables.length > 0) req.push(`- Data: ${ev.schema.tables.length} database table${ev.schema.tables.length === 1 ? '' : 's'} (see [the database reference](${relLink(path, DOC_PATHS.database)})).`);
    if (ev.auth.mechanisms.length > 0) req.push(`- Authentication: ${ev.auth.mechanisms.map((m) => m.name).join(', ')}.`);
    if (req.length === 0) return { notApplicable: 'There is no approved plan and nothing in the source states a requirement.' };
    uncertain.push('Functional requirements are not in the code; only technical requirements read from the source are listed.');
    sections.push(section('technical', `## Technical requirements (from the source)\n\n${req.join('\n')}`));
    sections.push(section('functional', `## Functional requirements\n\n${unverified('Functional requirements cannot be read from code. Add them outside this block, or save an approved project plan.')}`));
  } else if (which === 'implementation-plan' && !plan) {
    return { notApplicable: 'An implementation plan comes from an approved project plan; none was given.' };
  }
  return { targets: [{ path, doc: which, category: 'product', title, sections, uncertain }] };
}

// ── Type 2: architecture and engineering ────────────────────────────────────────────────────────

export function moduleDiagram(ev: Evidence): string | null {
  if (ev.modules.modules.length < 2 || ev.modules.edges.length === 0) return null;
  const nodes: FlowNode[] = ev.modules.modules.map((m) => ({ id: mermaidId(m.name, 'm'), label: `${m.name} (${m.files})` }));
  const edges: FlowEdge[] = ev.modules.edges.slice(0, 60).map((e) => ({ from: mermaidId(e.from, 'm'), to: mermaidId(e.to, 'm'), label: String(e.imports) }));
  return flowchart('LR', nodes, edges);
}

export function mmd(source: string, what: string): string {
  return `%% ${what}\n%% Generated by PawOS from the repository. Regenerated when the code changes — edit the source code, not this file.\n${source}\n`;
}

export function renderArchitecture(ev: Evidence): RenderOutcome {
  const path = DOC_PATHS.architecture;
  const codeFiles = ev.modules.modules.reduce((n, m) => n + m.files, 0);
  if (codeFiles === 0) return { notApplicable: 'No source files were found to describe.' };
  const uncertain = [...truncatedNote(ev)];
  const sections: ManagedSection[] = [];
  const overview = [`${ev.name} is written with ${ev.stack.length > 0 ? ev.stack.join(', ') : 'no framework PawOS recognises'}. PawOS read ${ev.filesRead} files${ev.truncated ? ' (not the whole project)' : ''}.`];
  const runtimes: string[] = [];
  if (ev.stack.includes('Electron')) {
    if (ev.paths.some((p) => p.startsWith('src/main/'))) runtimes.push('Electron main process (`src/main`)');
    if (ev.paths.some((p) => p.startsWith('src/renderer/'))) runtimes.push('Electron renderer (`src/renderer`)');
    if (ev.paths.some((p) => /(^|\/)preload\.[jt]s$/.test(p) || p.startsWith('src/preload/'))) runtimes.push('Electron preload bridge');
  }
  if (ev.stack.includes('Next.js')) runtimes.push('Next.js server and client components');
  if (ev.api.length > 0) runtimes.push(`HTTP API (${ev.api.length} endpoint${ev.api.length === 1 ? '' : 's'})`);
  if (ev.schema.tables.length > 0) runtimes.push(`Database schema (${ev.schema.tables.length} table${ev.schema.tables.length === 1 ? '' : 's'})`);
  if (runtimes.length > 0) overview.push(`Parts of the system found in the source:\n\n${runtimes.map((r) => `- ${r}`).join('\n')}`);
  sections.push(section('overview', `## Overview\n\n${overview.join('\n\n')}`));

  const diagram = moduleDiagram(ev);
  const targets: DocTarget[] = [];
  if (diagram) {
    const how = ev.modules.fromRuntimeGraph ? 'PawOS’s import graph of the project' : 'the import statements in the files PawOS read';
    sections.push(
      section(
        'module-map',
        `## Module dependencies\n\nEach box is an area of the code with its number of source files; an arrow means files in one area import files in the other, labelled with the number of imports. Derived from ${how}. Source: [${DIAGRAM_PATHS.modules}](${relLink(path, DIAGRAM_PATHS.modules)}).\n\n\`\`\`mermaid\n${diagram}\n\`\`\``
      )
    );
    targets.push({ path: DIAGRAM_PATHS.modules, doc: 'architecture', category: 'architecture', title: 'Module dependencies', whole: mmd(diagram, 'Module dependencies'), uncertain: [] });
    if (!ev.modules.fromRuntimeGraph) uncertain.push('Module edges come from scanning import statements (relative and `@/` imports only); package imports and dynamic imports are not shown.');
  } else {
    sections.push(section('module-map', `## Module dependencies\n\n_No imports between areas of the code were found._`));
  }
  sections.push(
    section(
      'modules',
      `## Areas of the code\n\n${table(
        ['Area', 'Files', 'Imports from'],
        ev.modules.modules.map((m) => [code(m.name), String(m.files), ev.modules.edges.filter((e) => e.from === m.name).map((e) => e.to).join(', ') || '—'])
      )}`
    )
  );
  if (ev.features.length > 0) {
    sections.push(section('features', `## Features\n\n${table(['Feature', 'Files'], ev.features.slice(0, 40).map((f) => [f.name, `${f.files.length} (${f.files.slice(0, 3).map(code).join(', ')}${f.files.length > 3 ? ', …' : ''})`]))}`));
  }
  const related: string[] = [];
  if (ev.schema.tables.length > 0) related.push(`[Database](${relLink(path, DOC_PATHS.database)})`);
  if (ev.api.length > 0) related.push(`[API](${relLink(path, DOC_PATHS.api)})`);
  if (ev.auth.mechanisms.length > 0) related.push(`[Authentication](${relLink(path, DOC_PATHS.auth)})`);
  if (ev.tests.files.length > 0) related.push(`[Testing](${relLink(path, DOC_PATHS.testing)})`);
  if (ev.deploy.files.length + ev.deploy.workflows.length > 0) related.push(`[Deployment](${relLink(path, DOC_PATHS.deployment)})`);
  if (related.length > 0) sections.push(section('related', `## Related documents\n\n${related.join(' · ')}`));
  targets.unshift({ path, doc: 'architecture', category: 'architecture', title: 'Architecture', sections, uncertain });
  return { targets };
}

export function renderDatabase(ev: Evidence): RenderOutcome {
  const path = DOC_PATHS.database;
  const { tables, relations, sources } = ev.schema;
  if (tables.length === 0) return { notApplicable: 'No SQL migrations or Prisma schema with tables were found.' };
  const uncertain = [...truncatedNote(ev)];
  const shown = tables.slice(0, 40);
  if (tables.length > shown.length) uncertain.push(`Only ${shown.length} of ${tables.length} tables are drawn in the diagram.`);
  const names = new Set(shown.map((t) => t.name));
  const entities: ErEntity[] = shown.map((t) => ({
    name: t.name,
    attributes: t.columns.slice(0, 14).map((c) => ({ type: c.type.replace(/\s+/g, '_') || 'unknown', name: c.name, key: c.primaryKey ? 'PK' : c.references ? 'FK' : c.unique ? 'UK' : undefined })),
  }));
  const rels: ErRelation[] = relations.filter((r) => names.has(r.from) && names.has(r.to)).map((r) => ({ from: r.to, to: r.from, cardinality: '||--o{', label: r.column }));
  const erd = erDiagram(entities, rels);
  const sections: ManagedSection[] = [
    section('overview', `## Overview\n\n${tables.length} table${tables.length === 1 ? '' : 's'}, read from ${sources.map((s) => fileLink(path, s)).slice(0, 12).join(', ')}${sources.length > 12 ? ` and ${sources.length - 12} more` : ''}. SQL migrations are applied in file-name order.`),
    section('erd', `## Entity relationships\n\nSource: [${DIAGRAM_PATHS.erd}](${relLink(path, DIAGRAM_PATHS.erd)}).\n\n\`\`\`mermaid\n${erd}\n\`\`\``),
  ];
  const detail = tables.map((t) => {
    const rows = t.columns.map((c) => [code(c.name), code(c.type), [c.primaryKey ? 'primary key' : '', c.unique ? 'unique' : '', c.nullable ? '' : 'not null', c.references ? `→ ${c.references}` : ''].filter(Boolean).join(', ') || '—']);
    const security = t.rowLevelSecurity ? `Row level security is on${t.policies.length > 0 ? `; policies: ${t.policies.map(code).join(', ')}` : ' (no policies found in the migrations)'}.` : 'Row level security is not enabled in the migrations read.';
    return `### ${t.name}\n\nDefined in ${fileLink(path, t.source)}. ${security}\n\n${rows.length > 0 ? table(['Column', 'Type', 'Constraints'], rows) : '_No columns could be read._'}`;
  });
  sections.push(section('tables', `## Tables\n\n${detail.join('\n\n')}`));
  if (tables.some((t) => t.columns.length === 0)) uncertain.push('Some tables have column definitions PawOS could not read.');
  return {
    targets: [
      { path, doc: 'database', category: 'architecture', title: 'Database', sections, uncertain },
      { path: DIAGRAM_PATHS.erd, doc: 'database', category: 'architecture', title: 'Database ERD', whole: mmd(erd, 'Database entity relationships'), uncertain: [] },
    ],
  };
}

export function renderApi(ev: Evidence): RenderOutcome {
  const path = DOC_PATHS.api;
  if (ev.api.length === 0) return { notApplicable: 'No API route handlers were found.' };
  const uncertain = [...truncatedNote(ev), 'The "Checks auth" column means the handler’s code mentions a session, user or token check. It is a pointer for review, not proof the route is protected.'];
  const groups = new Map<string, typeof ev.api>();
  for (const route of ev.api) {
    const key = route.route.split('/').slice(0, 3).join('/') || '/';
    (groups.get(key) ?? groups.set(key, []).get(key))?.push(route);
  }
  const body = [...groups]
    .map(([key, routes]) => `### ${code(key)}\n\n${table(['Method', 'Path', 'Handler', 'Checks auth', 'Notes'], routes.map((r) => [code(r.method), code(r.route), fileLink(path, r.path), r.checksAuth ? 'yes' : 'not seen', brief(r.description)]))}`)
    .join('\n\n');
  const frameworks = [...new Set(ev.api.map((a) => a.framework))];
  const sections = [
    section('overview', `## Overview\n\n${ev.api.length} endpoint${ev.api.length === 1 ? '' : 's'} (${frameworks.join(', ')}). Request and response shapes are not listed here: they are only documented where the handler’s own comments describe them.`),
    section('endpoints', `## Endpoints\n\n${body}`),
  ];
  return { targets: [{ path, doc: 'api', category: 'architecture', title: 'API', sections, uncertain }] };
}

export function renderAuth(ev: Evidence): RenderOutcome {
  const path = DOC_PATHS.auth;
  const rls = ev.schema.tables.filter((t) => t.rowLevelSecurity);
  if (ev.auth.mechanisms.length === 0 && ev.auth.middleware.length === 0 && rls.length === 0) return { notApplicable: 'No authentication code, middleware or row level security was found.' };
  const uncertain = ['This document shows where authentication code lives. It does not prove that every route or table is protected.'];
  const sections: ManagedSection[] = [];
  if (ev.auth.mechanisms.length > 0) {
    sections.push(section('mechanisms', `## Mechanisms\n\n${table(['Mechanism', 'Where'], ev.auth.mechanisms.map((m) => [m.name, m.files.slice(0, 6).map((f) => fileLink(path, f)).join(', ') + (m.files.length > 6 ? ` +${m.files.length - 6}` : '')]))}`));
  }
  if (ev.auth.middleware.length > 0) sections.push(section('middleware', `## Request middleware\n\n${list(ev.auth.middleware.map((m) => fileLink(path, m)), '')}`));
  if (rls.length > 0) {
    sections.push(section('row-level-security', `## Row level security\n\n${table(['Table', 'Policies'], rls.map((t) => [code(t.name), t.policies.length > 0 ? t.policies.map(code).join(', ') : 'none found']))}`));
  }
  const authEnv = ev.env.filter((e) => /AUTH|JWT|SESSION|OAUTH|CLIENT_ID|CLIENT_SECRET|SECRET|TOKEN|KEY/.test(e.name));
  if (authEnv.length > 0) sections.push(section('configuration', `## Configuration\n\nVariables the auth code depends on (names only):\n\n${list(authEnv.map((e) => code(e.name)), '')}`));
  return { targets: [{ path, doc: 'auth', category: 'architecture', title: 'Authentication and authorization', sections, uncertain }] };
}


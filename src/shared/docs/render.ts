export function adrPath(existingPaths: string[], title: string): { path: string; number: number } {
  let max = 0;
  for (const p of existingPaths) {
    const m = /^docs\/adr\/(\d{4})-[^/]+\.md$/.exec(p);
    if (m) max = Math.max(max, Number(m[1]));
  }
  const number = max + 1;
  return { path: `docs/adr/${String(number).padStart(4, '0')}-${slug(title)}.md`, number };
}

export function renderAdr(ev: Evidence, adr: AdrInput | undefined, date: string, existingPaths: string[]): RenderOutcome {
  const indexPath = DOC_PATHS.adr;
  const existing = existingPaths.filter((p) => /^docs\/adr\/\d{4}-[^/]+\.md$/.test(p)).sort();
  const targets: DocTarget[] = [];
  const all = [...existing];
  if (adr) {
    const { path, number } = adrPath(existingPaths, adr.title);
    all.push(path);
    const body = [
      `# ${number}. ${adr.title}`,
      '',
      `- **Status:** ${adr.status ?? 'accepted'}`,
      `- **Date:** ${date}`,
      '',
      '## Context',
      '',
      adr.context.trim(),
      '',
      '## Decision',
      '',
      adr.decision.trim(),
      '',
      '## Consequences',
      '',
      adr.consequences?.trim() || '_Not recorded._',
    ];
    if (adr.alternatives && adr.alternatives.length > 0) body.push('', '## Alternatives considered', '', ...adr.alternatives.map((a) => `- ${a}`));
    targets.push({ path, doc: 'adr', category: 'architecture', title: adr.title, whole: `${body.join('\n')}\n`, createOnly: true, uncertain: [] });
  }
  if (all.length === 0) return { notApplicable: 'There are no architecture decision records and no new decision was given.' };
  targets.push({
    path: indexPath,
    doc: 'adr',
    category: 'architecture',
    title: 'Architecture decisions',
    sections: [section('index', `## Decisions\n\n${all.sort().map((p) => `- [${basename(p).replace(/\.md$/, '')}](${relLink(indexPath, p)})`).join('\n')}`)],
    uncertain: [],
  });
  return { targets };
}


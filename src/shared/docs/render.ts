/** One page per component; a name used twice gets its folder appended. Stable for the same input. */
export function componentDocPaths(components: ComponentInfo[], folder: string): Map<ComponentInfo, string> {
  const counts = new Map<string, number>();
  for (const c of components) counts.set(c.name, (counts.get(c.name) ?? 0) + 1);
  const out = new Map<ComponentInfo, string>();
  for (const c of components) {
    const dup = (counts.get(c.name) ?? 0) > 1;
    const suffix = dup ? `-${slug(dirname(c.path).split('/').slice(-2).join('-'))}` : '';
    out.set(c, `${folder}/${c.name}${suffix}.md`);
  }
  return out;
}

function propsBlock(c: ComponentInfo): string {
  const lines: string[] = ['## Props', ''];
  if (c.propsType) lines.push(`Type: ${c.propsType === 'inline' ? 'declared inline' : code(c.propsType)}.`, '');
  if (c.props.length > 0) {
    lines.push(table(['Prop', 'Type', 'Required', 'Default', 'Description'], c.props.map((p) => [code(p.name), code(p.type), p.optional ? 'no' : 'yes', p.defaultValue !== undefined ? code(p.defaultValue) : '—', p.description ?? ''])));
  } else if (c.propsResolved) {
    lines.push('_This component takes no props._');
  }
  if (!c.propsResolved || c.uncertain) lines.push('', unverified(c.uncertain ?? 'The props could not be fully read from the source.'));
  return lines.join('\n');
}

export function renderComponentPage(c: ComponentInfo, docPath: string): DocTarget {
  const events = c.props.filter((p) => /^on[A-Z]/.test(p.name));
  const summary = [
    c.description ?? '',
    `**Source:** ${fileLink(docPath, c.path)} · ${c.exportKind === 'default' ? 'default export' : 'named export'}${c.clientOnly ? ' · client component (`"use client"`)' : ''}`,
  ].filter(Boolean);
  const sections: ManagedSection[] = [section('summary', summary.join('\n\n')), section('props', propsBlock(c))];
  if (events.length > 0) sections.push(section('events', `## Events\n\n${list(events.map((e) => `${code(e.name)} — ${code(e.type)}${e.description ? `: ${e.description}` : ''}`), '')}`));
  const stateLines: string[] = [];
  if (c.hooks.length > 0) stateLines.push(`Hooks: ${c.hooks.map(code).join(', ')}.`);
  if (c.states.length > 0) stateLines.push(`States the file handles (found from the identifiers it uses): ${c.states.join(', ')}.`);
  if (stateLines.length > 0) sections.push(section('states', `## State\n\n${stateLines.join('\n\n')}`));
  sections.push(section('usage', `## Used by\n\n${list(c.usedBy.map((u) => fileLink(docPath, u)), 'Not rendered by any file PawOS read.')}`));
  const uncertain = c.propsResolved && !c.uncertain ? [] : [`${c.name}: ${c.uncertain ?? 'props not fully read'}`];
  return { path: docPath, doc: c.kind === 'widget' ? 'widgets' : 'components', category: 'ui', title: c.name, sections, uncertain, sources: [c.path] };
}

export function renderComponents(ev: Evidence, kind: 'components' | 'widgets', max: number): RenderOutcome {
  const folder = kind === 'widgets' ? 'docs/widgets' : 'docs/components';
  const all = ev.components.filter((c) => (kind === 'widgets' ? c.kind === 'widget' : c.kind === 'component'));
  if (all.length === 0) return { notApplicable: kind === 'widgets' ? 'No components under a widgets/ folder were found.' : 'No exported React components were found.' };
  const paths = componentDocPaths(all, folder);
  const chosen = all.slice(0, max);
  const targets = chosen.map((c) => renderComponentPage(c, paths.get(c) ?? `${folder}/${c.name}.md`));
  const indexPath = DOC_PATHS[kind];
  const uncertain = [...truncatedNote(ev)];
  if (all.length > chosen.length) uncertain.push(`${all.length - chosen.length} more ${kind} were found than are documented in one run; run documentation again to cover them.`);
  const rows = all.map((c) => {
    const doc = paths.get(c);
    const documented = chosen.includes(c) && doc;
    return [documented ? `[${c.name}](${relLink(indexPath, doc)})` : c.name, fileLink(indexPath, c.path), c.propsResolved ? String(c.props.length) : `${c.props.length}?`, String(c.usedBy.length)];
  });
  targets.unshift({
    path: indexPath,
    doc: kind,
    category: 'ui',
    title: kind === 'widgets' ? 'Widgets' : 'Components',
    sections: [section('index', `## ${kind === 'widgets' ? 'Widgets' : 'Components'}\n\n${all.length} found. A “?” after the prop count means the props could not be fully read.\n\n${table(['Name', 'Source', 'Props', 'Used by'], rows)}`)],
    uncertain,
  });
  return { targets };
}

export function renderDesignSystem(ev: Evidence): RenderOutcome {
  const path = DOC_PATHS['design-system'];
  const d = ev.design;
  if (d.tokens.length === 0 && d.libraries.length === 0 && !d.tailwindConfig) return { notApplicable: 'No design tokens, UI libraries or Tailwind configuration were found.' };
  const sections: ManagedSection[] = [];
  const foundation: string[] = [];
  if (d.libraries.length > 0) foundation.push(`UI libraries: ${d.libraries.join(', ')}.`);
  if (d.tailwindConfig) foundation.push(`Tailwind configuration: ${fileLink(path, d.tailwindConfig)}.`);
  if (d.fonts.length > 0) foundation.push(`Font stacks: ${d.fonts.map(code).join('; ')}.`);
  if (d.stylesheets.length > 0) foundation.push(`Stylesheets read: ${d.stylesheets.length}.`);
  sections.push(section('foundation', `## Foundation\n\n${foundation.join('\n\n')}`));
  if (d.tokens.length > 0) {
    const groups = new Map<string, typeof d.tokens>();
    for (const t of d.tokens) {
      const g = /color|bg|background|fg|text|border|accent|primary|secondary|surface/i.test(t.name) ? 'Colour' : /space|gap|padding|margin|size|width|height/i.test(t.name) ? 'Spacing and size' : /radius|round/i.test(t.name) ? 'Radius' : /font|line|letter|weight/i.test(t.name) ? 'Typography' : /shadow|elevation/i.test(t.name) ? 'Elevation' : 'Other';
      (groups.get(g) ?? groups.set(g, []).get(g))?.push(t);
    }
    sections.push(section('tokens', `## Tokens\n\nCSS custom properties defined in the stylesheets (first definition of each).\n\n${[...groups].map(([g, ts]) => `### ${g}\n\n${table(['Token', 'Value', 'Defined in'], ts.map((t) => [code(t.name), code(t.value), fileLink(path, t.source)]))}`).join('\n\n')}`));
  }
  const counts = { components: ev.components.filter((c) => c.kind === 'component').length, widgets: ev.components.filter((c) => c.kind === 'widget').length };
  if (counts.components + counts.widgets > 0) sections.push(section('inventory', `## Component inventory\n\n${counts.components} components ([index](${relLink(path, DOC_PATHS.components)}))${counts.widgets > 0 ? `, ${counts.widgets} widgets ([index](${relLink(path, DOC_PATHS.widgets)}))` : ''}.`));
  return { targets: [{ path, doc: 'design-system', category: 'ui', title: 'Design system', sections, uncertain: ['Token purposes are grouped by name; how each token is meant to be used is not in the source.'] }] };
}

export function renderPages(ev: Evidence): RenderOutcome {
  const path = DOC_PATHS.pages;
  if (ev.pages.length === 0) return { notApplicable: 'No pages or routes were found.' };
  const byFile = new Map(ev.components.filter((c) => c.kind === 'page').map((c) => [c.path, c]));
  const rows = ev.pages.map((p) => {
    const c = byFile.get(p.path);
    return [code(p.route), fileLink(path, p.path), p.framework === 'react-router' ? `React Router${p.component ? ` → ${p.component}` : ''}` : p.framework === 'next-app' ? 'Next.js app router' : 'Next.js pages router', c && c.states.length > 0 ? c.states.join(', ') : '—'];
  });
  const sections = [
    section('routes', `## Routes\n\n${ev.pages.length} page${ev.pages.length === 1 ? '' : 's'}. “States” lists what the page file visibly handles (loading, error, empty…), read from the identifiers it uses.\n\n${table(['Route', 'File', 'Router', 'States'], rows)}`),
  ];
  return { targets: [{ path, doc: 'pages', category: 'ui', title: 'Pages and routes', sections, uncertain: ['Page states are found from identifiers in the page file only, not from the components it renders.'] }] };
}

export function uiFlowDiagram(ev: Evidence): string | null {
  if (ev.navigation.length === 0) return null;
  const routes = [...new Set(ev.navigation.flatMap((n) => [n.from, n.to]))].sort().slice(0, 40);
  const keep = new Set(routes);
  return flowchart(
    'LR',
    routes.map((r) => ({ id: mermaidId(r === '/' ? 'home' : r, 'r'), label: r, shape: 'round' as const })),
    ev.navigation.filter((n) => keep.has(n.from) && keep.has(n.to)).map((n) => ({ from: mermaidId(n.from === '/' ? 'home' : n.from, 'r'), to: mermaidId(n.to === '/' ? 'home' : n.to, 'r') }))
  );
}

export function renderUiFlows(ev: Evidence): RenderOutcome {
  const path = DOC_PATHS['ui-flows'];
  if (ev.pages.length < 2) return { notApplicable: 'Fewer than two pages were found, so there is no flow between pages.' };
  const diagram = uiFlowDiagram(ev);
  if (!diagram) {
    return {
      targets: [
        {
          path,
          doc: 'ui-flows',
          category: 'ui',
          title: 'UI flows',
          sections: [section('flow', '## Navigation\n\n_No links or redirects between pages were found in the page files or the components they import._')],
          uncertain: ['Navigation built at runtime (computed URLs, menus from data) is not visible to source analysis.'],
        },
      ],
    };
  }
  return {
    targets: [
      {
        path,
        doc: 'ui-flows',
        category: 'ui',
        title: 'UI flows',
        sections: [
          section(
            'flow',
            `## Navigation\n\nAn arrow means a page (or a component it imports) links, pushes or redirects to another page. Source: [${DIAGRAM_PATHS.uiFlow}](${relLink(path, DIAGRAM_PATHS.uiFlow)}).\n\n\`\`\`mermaid\n${diagram}\n\`\`\``
          ),
          section('links', `## Links\n\n${table(['From', 'To'], ev.navigation.map((n) => [code(n.from), code(n.to)]))}`),
        ],
        uncertain: ['Navigation built at runtime (computed URLs, menus from data) is not visible to source analysis.'],
      },
      { path: DIAGRAM_PATHS.uiFlow, doc: 'ui-flows', category: 'ui', title: 'UI flow', whole: mmd(diagram, 'Navigation between pages'), uncertain: [] },
    ],
  };
}
